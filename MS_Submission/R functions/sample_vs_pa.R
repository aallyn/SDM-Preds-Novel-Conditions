  p <- add_argument(p, "vs_pa_path", help = "A path to a list with the virtual species presence/absence data.")
  # Our second argument, the path to sf file to set spatial extent for the sampling
  p <- add_argument(p, "region_sf_path", help = "Either NULL or the file path to an sf polygon that will be used to limit the sampling area.")
  # Our third arugment, the path to a csv file with the sampling parameters, which get used by virtualSpecies::sampleOcurrences.
  p <- add_argument(p, "sample_vs_pa_params_path", help = "A file path that to the sample parameters file that will be used in virtualSpecies::sampleOcurrences.")
  # Our fourth argument, the path and name to save a list with sample presence/absence data
  p <- add_argument(p, "out_file", help = "The path and file name to save the sampled species presence/absence data. This is the full 'true' dataset.")
  # parse the arguments
  args <- parse_args(p)
  for (i in 1:length(args)) {
    log_info(paste0("Args include ", names(args)[i], ": ", args[[i]]))
  }

  # execute the function
  main_sample_vs_pa(vs_pa_path = args$vs_pa_path, region_sf_path = args$region_sf_path, sample_vs_pa_params_path = args$sample_vs_pa_params_path, out_file = args$out_file)

  # update logger
  log_info("Virtual species presence/absences sampled and saved.")
}